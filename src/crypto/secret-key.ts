import { bls12_381, bls12_381_Fr } from "@noble/curves/bls12-381";
import { ed25519 } from "@noble/curves/ed25519";
import { secp256k1 } from "@noble/curves/secp256k1";
import { hmac } from "@noble/hashes/hmac.js";
import { sha256 } from "@noble/hashes/sha2.js";
import { bytesToHex as toHex, concatBytes } from "@noble/hashes/utils.js";
import { bytesToBs58, hexToBytes, toBytes, type BytesLike } from "./bytes";
import { blake3Hash } from "./hash";
import { PublicKey } from "./public-key";
import { Signature, SignatureKind } from "./signature";
import {
  ID_RAW,
  keygen as keygenFnDsa,
  normalize_sign_key,
  public_key_from_sign_key,
  sign as signFnDsa512Raw,
} from "../vendor/fndsa.js";

const BLS12381_SCALAR_ORDER = bls12_381_Fr.ORDER;

export const SecretKeyKind = Object.freeze({
  CLASSICAL: "CLASSICAL",
  FN_DSA512: "FN_DSA512",
});
export type SecretKeyKind = typeof SecretKeyKind[keyof typeof SecretKeyKind];

export class SecretKey {
  static readonly LENGTH = 32;
  static readonly CLASSICAL_LENGTH = 32;
  static readonly FN_DSA512_LENGTH = 1281;

  readonly kind: SecretKeyKind;
  readonly bytes: Uint8Array;

  static from(value: SecretKey | BytesLike): SecretKey {
    if (value instanceof SecretKey) return value;
    if (typeof value === "string") return SecretKey.fromHex(value);
    return SecretKey.fromBytes(value);
  }

  static fromBytes(bytes: BytesLike): SecretKey {
    return new SecretKey(bytes);
  }

  static fromHex(hex: string): SecretKey {
    return new SecretKey(hexToBytes(hex));
  }

  /**
   * Generates one 32-byte classical key shared by Ed25519, secp256k1, and
   * BLS12-381. The generated bytes are also a valid secp256k1 scalar.
   */
  static generateClassical(): SecretKey {
    return new SecretKey(secp256k1.utils.randomSecretKey());
  }

  /** Alias for generateClassical(). */
  static generate(): SecretKey {
    return SecretKey.generateClassical();
  }

  /** @deprecated Use generateClassical(). */
  static generateEd25519(): SecretKey {
    return SecretKey.generateClassical();
  }

  /** @deprecated Use generateClassical(). */
  static generateSecp256k1(): SecretKey {
    return SecretKey.generateClassical();
  }

  /** @deprecated Use generateClassical(). */
  static generateBls12381(): SecretKey {
    return SecretKey.generateClassical();
  }

  static generateFnDsa512(): SecretKey {
    return new SecretKey(keygenFnDsa(9).sign_key);
  }

  static generateDsa512(): SecretKey {
    return SecretKey.generateFnDsa512();
  }

  constructor(bytes: BytesLike) {
    const raw = toBytes(bytes);
    if (raw.length === SecretKey.CLASSICAL_LENGTH) {
      this.kind = SecretKeyKind.CLASSICAL;
    } else if (raw.length === SecretKey.FN_DSA512_LENGTH) {
      this.kind = SecretKeyKind.FN_DSA512;
    } else {
      throw new TypeError(
        `SecretKey must be ${SecretKey.CLASSICAL_LENGTH} or ${SecretKey.FN_DSA512_LENGTH} bytes`,
      );
    }
    this.bytes = raw;
  }

  async ed25519Public(): Promise<PublicKey> {
    this.assertClassical("ed25519Public");
    return PublicKey.fromBytes(ed25519.getPublicKey(this.bytes));
  }

  async secp256k1Public(): Promise<PublicKey> {
    this.assertClassical("secp256k1Public");
    return PublicKey.fromBytes(secp256k1.getPublicKey(this.bytes, true));
  }

  async bls12381Public(): Promise<PublicKey> {
    this.assertClassical("bls12381Public");
    const scalar = await deriveBls12381Scalar(this.bytes);
    return PublicKey.fromBytes(bls12_381.getPublicKey(scalar));
  }

  async fnDsa512Public(): Promise<PublicKey> {
    this.assertFnDsa512("fnDsa512Public");
    return PublicKey.fromBytes(public_key_from_sign_key(normalize_sign_key(this.bytes)));
  }

  async signFnDsa512(message: BytesLike): Promise<Signature> {
    this.assertFnDsa512("signFnDsa512");
    const signature = signFnDsa512Raw(
      normalize_sign_key(this.bytes),
      new Uint8Array(),
      ID_RAW,
      toBytes(message),
    );
    return new Signature(SignatureKind.FN_DSA512, signature);
  }

  async signEd25519(message: BytesLike): Promise<Signature> {
    this.assertClassical("signEd25519");
    const signature = ed25519.sign(toBytes(message), this.bytes);
    return new Signature(SignatureKind.ED25519, signature);
  }

  async signSecp256k1(message: BytesLike): Promise<Signature> {
    this.assertClassical("signSecp256k1");
    const bytes = toBytes(message);
    const digest = bytes.length === 32 ? bytes : blake3Hash(bytes);
    const signature = secp256k1.sign(digest, this.bytes, {
      prehash: false,
    });
    const compact = signature.normalizeS().toCompactRawBytes();
    return new Signature(
      SignatureKind.SECP256K1,
      new Uint8Array([...compact, signature.recovery + 27]),
    );
  }

  async signBls12381(message: BytesLike): Promise<Signature> {
    this.assertClassical("signBls12381");
    const scalar = await deriveBls12381Scalar(this.bytes);
    const signature = bls12_381.sign(toBytes(message), scalar);
    return new Signature(SignatureKind.BLS12381, signature);
  }

  toHex(prefix = false): string {
    return `${prefix ? "0x" : ""}${toHex(this.bytes)}`;
  }

  toBs58(): string {
    return bytesToBs58(this.bytes);
  }

  toJSON(): { kind: SecretKeyKind; hex: string } {
    return { kind: this.kind, hex: this.toHex() };
  }

  private assertClassical(method: string): void {
    if (this.kind !== SecretKeyKind.CLASSICAL) {
      throw new TypeError(`${method} is only available for 32-byte classical secret keys`);
    }
  }

  private assertFnDsa512(method: string): void {
    if (this.kind !== SecretKeyKind.FN_DSA512) {
      throw new TypeError(`${method} is only available for FN_DSA512 secret keys`);
    }
  }
}

function toArrayBuffer(bytes: Uint8Array): ArrayBuffer {
  const buffer = new ArrayBuffer(bytes.length);
  new Uint8Array(buffer).set(bytes);
  return buffer;
}

async function deriveBls12381Scalar(seed: Uint8Array): Promise<Uint8Array> {
  let salt: Uint8Array = new Uint8Array(
    toArrayBuffer(new TextEncoder().encode("BLS-SIG-KEYGEN-SALT-")),
  );
  let scalar = 0n;
  const ikm: Uint8Array = new Uint8Array(
    toArrayBuffer(new Uint8Array([...seed, 0])),
  );
  const info: Uint8Array = new Uint8Array(
    toArrayBuffer(new Uint8Array([0, 48])),
  );

  while (scalar === 0n) {
    salt = copyBytes(sha256(salt));
    const prk = copyBytes(hmac(sha256, salt, ikm));
    let previous: Uint8Array = new Uint8Array(new ArrayBuffer(0));
    let okm: Uint8Array = new Uint8Array(new ArrayBuffer(0));

    for (let counter = 1; okm.length < 48; counter += 1) {
      previous = copyBytes(hmac(sha256, prk, concatBytes(previous, info, Uint8Array.of(counter))));
      okm = concatBytes(okm, previous);
    }

    scalar = bytesToBigInt(okm.slice(0, 48)) % BLS12381_SCALAR_ORDER;
  }

  return bigIntTo32Bytes(scalar);
}

function bytesToBigInt(bytes: Uint8Array): bigint {
  let value = 0n;
  for (const byte of bytes) {
    value = (value << 8n) | BigInt(byte);
  }
  return value;
}

function bigIntTo32Bytes(value: bigint): Uint8Array {
  const bytes = new Uint8Array(32);
  let remaining = value;
  for (let i = 31; i >= 0; i -= 1) {
    bytes[i] = Number(remaining & 0xffn);
    remaining >>= 8n;
  }
  return bytes;
}

function copyBytes(bytes: Uint8Array): Uint8Array {
  return new Uint8Array(toArrayBuffer(bytes));
}
